#Requires -Version 5.1
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = $PSScriptRoot
$pages = Join-Path $root 'pages'
$index = Join-Path $root 'index.html'
$marker = '<!-- generated-html-library -->'
if (Test-Path -LiteralPath $index) {
    if (-not ([IO.File]::ReadAllText($index).Contains($marker))) {
        throw 'Existing index.html is not generated by this library. Preserve it before setting up the library.'
    }
}
if (-not (Test-Path -LiteralPath $pages -PathType Container)) {
    throw 'The pages directory is missing.'
}
$items = @(Get-ChildItem -LiteralPath $pages -Recurse -Force)
if (@($items | Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint }).Count) {
    throw 'Symbolic links and junctions are not supported inside pages.'
}
$files = @($items | Where-Object { -not $_.PSIsContainer -and $_.Extension -match '^\.html?$' } |
    Sort-Object FullName)
$links = foreach ($file in $files) {
    $relative = $file.FullName.Substring($pages.Length + 1).Replace('\', '/')
    $url = 'pages/' + (($relative.Split('/') | ForEach-Object { [Uri]::EscapeDataString($_) }) -join '/')
    $label = [Net.WebUtility]::HtmlEncode($relative)
    '        <li><a href="' + $url + '"><span>' + $label + '</span><span class="arrow" aria-hidden="true">&#8599;</span></a></li>'
}
$template = [IO.File]::ReadAllText((Join-Path $root 'index.template.html'))
if (-not $template.Contains($marker) -or -not $template.Contains('{{FILE_LIST}}')) {
    throw 'Invalid index template.'
}
$html = $template.Replace('{{FILE_LIST}}', ($links -join "`n")).Replace('{{FILE_COUNT}}', [string]$files.Count)
[IO.File]::WriteAllText($index, $html, (New-Object Text.UTF8Encoding $false))
Write-Host ('Index updated: {0} HTML files.' -f $files.Count)
